/**
 * @file main.c
 * @brief ラインレースカーの全体統括メインファイル（初期化シーケンス対応版）
 * @details 起動時の1回きりの初期化フェーズを経てから、
 *          スタンバイ状態に移行してメインループの巡回制御を開始します。
 */

// 1. 必要なヘッダーファイルのインクルード
#include <stdio.h>
#include "global.h"     // システム共通の変数や enum の定義
#include "input.h"      // センサー入力担当
#include "compute.h"    // 計算・状態遷移担当
#include "output.h"     // モーター出力担当
#include "led_lcd.h"    // LED ＆ LCD表示担当
#include "music.h"      // サウンド・音楽担当

// ==========================================
// 外部モジュールの関数プロトタイプ宣言
// （ヘッダーファイルを使わない場合の記述）
// ==========================================

// void Input_Task(void);
// void Compute_Task(void);
// void Output_Task(void);

/**
 * @brief メイン関数（プログラムのスタート地点）
 */
int main(void) {
    // -----------------------------------------------------------------
    // ステップ 1: 起動直後の初期化フェーズ（Boot & Init）
    // -----------------------------------------------------------------
    // まずシステム状態を「初期化（INIT）」にセット
    g_system_state = STATE_INIT;

    // 【重要】whileに入る前に、初期化状態のまま全タスクを1回だけ通すことで、
    // 各モジュールの変数のクリアや初期設定を安全に済ませる
    Input_Task();
    Compute_Task();
    Output_Task();
    Led_Lcd_Task();
    Music_Task();

    // -----------------------------------------------------------------
    // ステップ 2: スタンバイ状態への移行
    // -----------------------------------------------------------------
    // 初期化が無事に終わったので、状態を「スタンバイ（待機中）」に切り替える
    g_system_state = STATE_STANDBY;

    // -----------------------------------------------------------------
    // ステップ 3: メインループ（通常運転開始）
    // -----------------------------------------------------------------
    // スタンバイ状態以降は、この無限ループで全タスクを永遠に巡回し続ける
    while (1) {
        
        // 1. 入力タスク：センサーやスイッチの現状を読み取る
        Input_Task();

        // 2. 計算タスク：現在の状態（スタンバイやランニング等）やセンサー値をもとに判断する
        Compute_Task();

        // 3. 出力タスク：計算結果をもとに、実際にモーターを動かす
        Output_Task();

        // 4. LED & LCDタスク：現在のステータスを画面やランプに表示する
        Led_Lcd_Task();

        // 5. ミュージックタスク：状態に応じたサウンドを奏でる
        Music_Task();

    }

    // マイコンのプログラムでは無限ループのためここには到達しません
    return 0;
}

// ==========================================
// 【プロトタイプ宣言の役割と、プログラムがたどる全ルート】
//
// 1. 【コンパイル時の動き（なぜ宣言が必要か？）】
//    - コンパイラはファイルを「上から下へ1行ずつ」しか読めません。
//    - main() の上にあるプロトタイプ宣言（予告）を先に読むことで、コンパイラは
//      「なるほど、この名前の関数は後から（または別のファイルに）実体があるんだな」と安心し、
//      エラーを出さずにコンパイルを進めることができます。
//
// 2. 【リンク時の動き（実体への結びつき）】
//    - プロトタイプ宣言はあくまで「名前と形の看板」にすぎません。
//    - コンパイルのあと、リンカ（Linker）という仕組みがこの看板を頼りにして、
//      別ファイルの「input.c」や「compute.c」にある本物の関数（実体）を探し出し、
//      ドッキングさせて一つの実行ファイルに組み上げます。
//
// 3. 【実行時の動き（ジャンプと復帰）】
//    - プログラムが実際に動き出し、int main() の中で Input_Task() が呼ばれると、
//      CPUはリンカが繋いでくれた道を通って、
//      別ファイル（input.c）にある「本物の関数の中身」へジャンプします。
//    - 中の処理をすべて終えると、CPUはちゃんと main() の呼び出し元の場所へ帰ってきます。
//
// 4. 【サブ関数のスコープとプロトタイプ宣言のルール】
//    - input.c の中で使われる「細かいサブ関数」は、あくまでその input.c の中で完結するものです。
//    - main.c のプロトタイプ宣言に書く必要はありません（書くべきではありません）。
//    - input.c 内だけで使われるサブ関数は、input.c のファイルの先頭（または呼び出すより上）で
//      個別にプロトタイプ宣言するか、順番を上に定義しておけば、そのファイル内で完結して動きます。
// ==========================================

